"""Optional local go2rtc video relay; HTTP management listens only on loopback.

WebRTC media uses UDP/TCP port 8555. Signaling is proxied through PiNVR's
authenticated API and never exposes the go2rtc management API to browsers.
"""
import json
import os
import subprocess
import threading
from pathlib import Path
from urllib.parse import quote

RELAY_PROCESS = None
RELAY_LOCK = threading.RLock()
RELAY_BINARY = Path(os.environ.get('PINVR_GO2RTC', '/opt/pinvr/bin/go2rtc'))
RELAY_CONFIG = Path(os.environ.get('PINVR_DATA', '/var/lib/pinvr')) / 'go2rtc.yaml'


def safe_url(camera, sub=False):
    name = quote(camera['username'] or '', safe='')
    password = quote(camera['password'] or '', safe='')
    auth = f'{name}:{password}@' if name else ''
    path = camera['sub_path'] if sub else camera['main_path']
    return f'rtsp://{auth}{camera["host"]}{path}'


def restart_relay(cameras):
    global RELAY_PROCESS
    with RELAY_LOCK:
        if RELAY_PROCESS and RELAY_PROCESS.poll() is None:
            RELAY_PROCESS.terminate()
            try: RELAY_PROCESS.wait(timeout=4)
            except subprocess.TimeoutExpired: RELAY_PROCESS.kill()
        RELAY_PROCESS = None
        if not RELAY_BINARY.is_file() or not os.access(RELAY_BINARY, os.X_OK):
            return False
        config = ['# Autogenerated by PiNVR; DO NOT expose this file',
                  'api:', '  listen: "127.0.0.1:1984"',
                  '  allow_paths: [/api/webrtc]',
                  'rtsp:', '  listen: ""',
                  'webrtc:', '  listen: ":8555"',
                  '  ice_servers: []',
                  'streams:']
        for cam in cameras:
            if not cam['enabled']:continue
            for profile, sub in [('main', False), ('sub', True)]:
                config.append(f'  cam{cam["id"]}_{profile}: {json.dumps(safe_url(cam, sub))}')
        RELAY_CONFIG.parent.mkdir(parents=True, exist_ok=True)
        RELAY_CONFIG.write_text('\n'.join(config)+'\n')
        os.chmod(RELAY_CONFIG, 0o600)
        try:
            RELAY_PROCESS = subprocess.Popen([str(RELAY_BINARY), '-config', str(RELAY_CONFIG)],
                                             stdin=subprocess.DEVNULL,
                                             stdout=subprocess.DEVNULL,
                                             stderr=subprocess.DEVNULL,
                                             start_new_session=True)
            return True
        except OSError:
            return False


def stop_relay():
    global RELAY_PROCESS
    with RELAY_LOCK:
        if RELAY_PROCESS and RELAY_PROCESS.poll() is None:
            RELAY_PROCESS.terminate()
            try: RELAY_PROCESS.wait(timeout=4)
            except subprocess.TimeoutExpired: RELAY_PROCESS.kill()
        RELAY_PROCESS = None


def is_running():
    with RELAY_LOCK:
        return RELAY_PROCESS is not None and RELAY_PROCESS.poll() is None
